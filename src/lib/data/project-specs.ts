export function getProjectSpecs(
  projectName: string,
  district: string | null,
  projectType: string | null
): ProjectSpecInfo {
  const normName = projectName.replaceAll(/\s+/g, "");

  for (const [key, spec] of Object.entries(MAJOR_PROJECTS_SPECS)) {
    if (normName.includes(key)) {
      return spec;
    }
  }

  // If not in verified dictionary, return honest null/unconfirmed status
  const isRecon = (projectType ?? "").includes("재건축");
  return {
    totalUnits: null,
    memberUnits: null,
    generalUnits: null,
    rentalUnits: null,
    generalRatio: null,
    far: isRecon ? "서울시 조례 상한(약 250~300%)" : "서울시 조례 상한(약 220~250%)",
    bcr: "20% 이하",
    floors: isRecon ? "최고 35층 내외" : "최고 29층 내외",
    builder: null,
    statusNote: "인가 고시문 및 사업시행계획 수립에 따라 확정 예정",
  };
}
