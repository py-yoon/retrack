const DISTRICT_REGEX = new RegExp(`(${SEOUL_DISTRICTS.join("|")})`);

/**
 * 텍스트 또는 행정코드로부터 서울시 자치구를 판별합니다.
 * @param {Object} params
 * @param {string} [params.text] - 주소, 사업장명 등 텍스트
 * @param {string[]} [params.codes] - PRJC_CD, RPT_MNG_CD 등 5자리 행정코드 접두사를 가진 코드 목록
 * @returns {string|null} - 판별된 자치구명 (예: '강남구') 또는 null
 */
export function resolveDistrict({ text = "", codes = [] } = {}) {
  // 1. 텍스트 내 자치구 직명 일치 (예: '강남구 대치동')
  const directMatch = text.match(DISTRICT_REGEX);
  if (directMatch) return directMatch[1];

  // 2. 5자리 행정코드 접두사 매칭
  for (const code of codes) {
    if (!code) continue;
    const prefix = String(code).slice(0, 5);
    if (DISTRICT_CODE_MAP[prefix]) {
      return DISTRICT_CODE_MAP[prefix];
    }
  }

  // 3. 법정동 및 지역 키워드 매칭
  for (const [dong, district] of Object.entries(DONG_DISTRICT_MAP)) {
    if (text.includes(dong)) {
      return district;
    }
  }

  return null;
}
